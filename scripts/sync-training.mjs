/**
 * sync-training.mjs
 * Compiles all training content into lib/training-compiled.ts.
 * Sources:
 *   1. brand-architect-portal/training-data/ — portal-specific files
 *   2. ~/Desktop/training-data/             — Jeremy Haynes PDFs + transcripts
 * Supports: .txt and .pdf files, recurses into subdirectories.
 */

import fs from 'fs';
import path from 'path';
import os from 'os';
import { fileURLToPath } from 'url';
import { createRequire } from 'module';

const require = createRequire(import.meta.url);
const pdfParse = require('pdf-parse');

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.join(__dirname, '..');
const OUT_FILE = path.join(ROOT, 'lib', 'training-compiled.ts');

// Source directories to scan
const SOURCE_DIRS = [
  path.join(ROOT, 'training-data'),
  path.join(os.homedir(), 'Desktop', 'training-data'),
];

// ─── File discovery (recursive) ──────────────────────────────────────────────

// Only include .txt files — SooWei's own transcripts and content, no external PDFs
function findFiles(dir, exts = ['.txt'], skipFiles = ['HOW-TO-ADD-CONTENT.txt']) {
  if (!fs.existsSync(dir)) return [];
  let entries;
  try { entries = fs.readdirSync(dir, { withFileTypes: true }); } catch { return []; }
  const results = [];
  for (const entry of entries) {
    const fullPath = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      results.push(...findFiles(fullPath, exts, skipFiles));
    } else if (exts.some(e => entry.name.toLowerCase().endsWith(e)) && !skipFiles.includes(entry.name)) {
      results.push(fullPath);
    }
  }
  return results;
}

// ─── Text extraction ──────────────────────────────────────────────────────────

async function extractText(filePath) {
  if (filePath.toLowerCase().endsWith('.pdf')) {
    try {
      const buffer = fs.readFileSync(filePath);
      const data = await pdfParse(buffer);
      return data.text?.trim() ?? '';
    } catch (e) {
      console.warn(`  ⚠ Could not parse PDF: ${path.basename(filePath)} — ${e.message}`);
      return '';
    }
  }
  return fs.readFileSync(filePath, 'utf-8').trim();
}

// ─── Main ─────────────────────────────────────────────────────────────────────

const seenNames = new Set();
const allFiles = [];

for (const dir of SOURCE_DIRS) {
  const files = findFiles(dir);
  for (const f of files) {
    // Use relative path from source dir as a dedup key
    const rel = path.relative(dir, f);
    if (!seenNames.has(rel)) {
      seenNames.add(rel);
      allFiles.push({ filePath: f, label: rel });
    }
  }
}

if (allFiles.length === 0) {
  console.log('[training-sync] No files found — writing empty export.');
  fs.writeFileSync(OUT_FILE,
    `// Auto-generated\nexport const TRAINING_DOCS: { filename: string; content: string }[] = [];\n`
  );
  process.exit(0);
}

console.log(`[training-sync] Processing ${allFiles.length} file(s)...`);

const docs = [];
for (const { filePath, label } of allFiles) {
  const content = await extractText(filePath);
  if (content.length < 50) continue; // skip near-empty files
  docs.push({ filename: label, content });
  console.log(`  ✓ ${label} (${content.length.toLocaleString()} chars)`);
}

const lines = [
  '// Auto-generated by scripts/sync-training.mjs — do not edit manually',
  'export const TRAINING_DOCS: { filename: string; content: string }[] = [',
  ...docs.map(({ filename, content }) => {
    const safe = content.replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$\{/g, '\\${');
    return `  { filename: ${JSON.stringify(filename)}, content: \`${safe}\` },`;
  }),
  '];',
];

fs.writeFileSync(OUT_FILE, lines.join('\n') + '\n');
console.log(`[training-sync] Compiled ${docs.length} doc(s) → lib/training-compiled.ts`);
